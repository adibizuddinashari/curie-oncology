// Generates the WordPress theme templates (wp-theme/curie/) from the same
// src/pages + src/partials the static build uses, so there is one source of
// truth for markup. Only the regions marked <!-- @cms name key=value --> ...
// <!-- @/cms --> are swapped for PHP template parts that read WP content.
//
// Hand-written theme files (functions.php, inc/, template-parts/,
// single-doctor.php, index.php) are never touched by this script.

const fs = require("fs");
const path = require("path");
const { pages, NAV_KEYS } = require("./build");

const ROOT = path.join(__dirname, "..");
const SRC = __dirname;
const THEME = path.join(ROOT, "wp-theme", "curie");

const read = (p) => fs.readFileSync(path.join(SRC, p), "utf8");

// Static file → WP route key (see curie_url() in inc/helpers.php).
const ROUTES = {
  "index.html": "home",
  "about.html": "about",
  "meet-our-doctors.html": "doctors",
  "our-services.html": "services",
  "health-education.html": "resources",
  "contact-us.html": "contact",
};

// Static file → theme template file.
const TEMPLATES = {
  "index.html": "front-page.php",
  "about.html": "page-about.php",
  "meet-our-doctors.html": "page-our-doctors.php",
  "our-services.html": "page-oncology-services.php",
  "health-education.html": "page-resource-centre.php",
  "contact-us.html": "page-contact-us.php",
};

const phpStr = (s) => "'" + String(s).replace(/\\/g, "\\\\").replace(/'/g, "\\'") + "'";

function toPhp(html) {
  return (
    html
      // CMS regions → template parts (args become the $args array).
      .replace(/([ \t]*)<!-- @cms ([\w-]+)([^>]*?)\s*-->\n[\s\S]*?<!-- @\/cms -->\n/g, (_, indent, name, rawArgs) => {
        const args = [...rawArgs.matchAll(/([\w-]+)=([\w-]+)/g)].map(([, k, v]) => `${phpStr(k)} => ${phpStr(v)}`);
        const argPhp = args.length ? `, null, array( ${args.join(", ")} )` : "";
        return `${indent}<?php get_template_part( 'template-parts/${name}'${argPhp} ); ?>\n`;
      })
      // Internal page links.
      .replace(/href="([a-z-]+)\.html(#[^"]*)?"/g, (m, file, hash = "") => {
        const key = ROUTES[`${file}.html`];
        if (key) return `href="<?php echo esc_url( curie_url( '${key}' ) ); ?>${hash}"`;
        if (file.startsWith("dr-")) return `href="<?php echo esc_url( curie_doctor_url( '${file}' ) ); ?>${hash}"`;
        throw new Error(`Unmapped link: ${m}`);
      })
      // Theme assets.
      .replace(/(['"(])assets\//g, "$1<?php echo CURIE_ASSETS; ?>/")
  );
}

function writeTheme(file, content) {
  fs.writeFileSync(path.join(THEME, file), content);
  console.log(`theme ${file}`);
}

const GENERATED = "<?php /* Generated by src/build-theme.js from src/ - edit the source, not this file. */ ?>\n";

// header.php: <head> from shell.html (CSS is enqueued in functions.php) + header partial.
const shell = read("partials/shell.html");
const head = shell
  .slice(0, shell.indexOf("{{HEADER}}"))
  .replace("{{TITLE}}", "<?php echo esc_html( curie_meta( 'title' ) ); ?>")
  .replace("{{DESCRIPTION}}", "<?php echo esc_attr( curie_meta( 'description' ) ); ?>")
  .replace(/\s*<link rel="stylesheet"[^>]*>/, "")
  .replace("</head>", "  <?php wp_head(); ?>\n</head>")
  .replace("<body>", "<body <?php body_class(); ?>>\n<?php wp_body_open(); ?>");
let header = read("partials/header.html");
for (const key of NAV_KEYS) header = header.replaceAll(`{{NAV_${key}}}`, `<?php curie_nav_class( '${key}' ); ?>`);
writeTheme("header.php", GENERATED + toPhp(head + header) + "\n  <main>\n");

// footer.php
writeTheme("footer.php", GENERATED + "  </main>\n" + toPhp(read("partials/footer.html")) + "\n<?php wp_footer(); ?>\n</body>\n</html>\n");

// Page templates.
for (const page of pages) {
  const template = TEMPLATES[page.file];
  if (!template) continue; // doctor profiles render from single-doctor.php
  const meta = `<?php\ncurie_set_meta( array(\n\t'title'       => ${phpStr(page.title)},\n\t'description' => ${phpStr(page.description)},\n\t'nav'         => ${phpStr(page.nav)},\n) );\nget_header();\n?>\n`;
  writeTheme(template, GENERATED + meta + toPhp(read(`pages/${page.src}`)) + "\n<?php get_footer(); ?>\n");
}

// Assets (gitignored inside the theme; deployment copies them the same way).
fs.cpSync(path.join(ROOT, "assets"), path.join(THEME, "assets"), { recursive: true });
console.log("theme assets/ copied");
